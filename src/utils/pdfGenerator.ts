import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { AnalysisStep, ComponentValues } from '../engine/types';
import { fmt, fmtFraction } from '../engine/matrixSolver';

interface PDFReportData {
  theorem: 'thevenin' | 'norton';
  circuitId: number;
  circuitName: string;
  circuitDescription: string;
  values: ComponentValues;
  steps: AnalysisStep[];
  vth: number;
  rth: number;
  inVal: number;
  rn: number;
  il: number;
  vl: number;
  pl: number;
  rl: number;
}

export function generatePDFReport(data: PDFReportData): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 15;
  let y = margin;

  // Primary Theme Colors (Gold & Dark Charcoal)
  const primaryGold = [202, 138, 4]; // #ca8a04
  const darkCharcoal = [26, 26, 26]; // #1a1a1a
  const softGray = [100, 100, 100];

  // Helper: Draw Header Bar
  const drawHeader = () => {
    doc.setFillColor(darkCharcoal[0], darkCharcoal[1], darkCharcoal[2]);
    doc.rect(0, 0, pageWidth, 24, 'F');

    doc.setFillColor(primaryGold[0], primaryGold[1], primaryGold[2]);
    doc.rect(0, 24, pageWidth, 1.5, 'F');

    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.text('CircuitLAB — Electrical Engineering Simulation Report', margin, 12);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.setTextColor(220, 220, 220);
    doc.text(
      `Deterministic Network Analysis | ${data.theorem === 'thevenin' ? "Thevenin's Theorem" : "Norton's Theorem"}`,
      margin,
      18
    );

    doc.setTextColor(primaryGold[0], primaryGold[1], primaryGold[2]);
    doc.setFont('helvetica', 'bold');
    doc.text('SIMULATION REPORT', pageWidth - margin - 38, 15);
  };

  // Helper: Draw Footer with Page Number
  const totalPagesExp = '{total_pages_count_string}';
  const drawFooter = (pageNum: number) => {
    doc.setDrawColor(200, 200, 200);
    doc.setLineWidth(0.5);
    doc.line(margin, pageHeight - 12, pageWidth - margin, pageHeight - 12);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(softGray[0], softGray[1], softGray[2]);
    doc.text('Generated by CircuitLAB DC Network Simulation Engine', margin, pageHeight - 7);
    doc.text(
      `Page ${pageNum}`,
      pageWidth - margin - 15,
      pageHeight - 7
    );
  };

  // --- PAGE 1: HEADER & OVERVIEW ---
  drawHeader();
  y = 33;

  // Title Section
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(darkCharcoal[0], darkCharcoal[1], darkCharcoal[2]);
  doc.text(
    `${data.theorem === 'thevenin' ? "THEVENIN'S THEOREM" : "NORTON'S THEOREM"} SIMULATION REPORT`,
    margin,
    y
  );
  y += 7;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(softGray[0], softGray[1], softGray[2]);
  doc.text(
    `Date: ${new Date().toLocaleDateString()} | CircuitLAB Engineering Report`,
    margin,
    y
  );
  y += 7;

  // Student Academic Information Box
  doc.setFillColor(250, 250, 252);
  doc.setDrawColor(210, 210, 218);
  doc.setLineWidth(0.5);
  doc.roundedRect(margin, y, pageWidth - 2 * margin, 13, 1.5, 1.5, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(darkCharcoal[0], darkCharcoal[1], darkCharcoal[2]);
  doc.text('Student Name:', margin + 4, y + 4.8);
  doc.setFont('helvetica', 'normal');
  doc.text('KDNSP Abhiram', margin + 28, y + 4.8);

  doc.setFont('helvetica', 'bold');
  doc.text('Roll Number:', margin + 95, y + 4.8);
  doc.setFont('helvetica', 'normal');
  doc.text('26211A05N2', margin + 118, y + 4.8);

  doc.setFont('helvetica', 'bold');
  doc.text('Branch:', margin + 4, y + 9.8);
  doc.setFont('helvetica', 'normal');
  doc.text('CSE D', margin + 28, y + 9.8);

  doc.setFont('helvetica', 'bold');
  doc.text('Institution:', margin + 95, y + 9.8);
  doc.setFont('helvetica', 'normal');
  doc.text('BVRIT Narsapur', margin + 118, y + 9.8);

  y += 17;

  // Circuit Configuration Overview Box
  doc.setFillColor(248, 248, 248);
  doc.setDrawColor(primaryGold[0], primaryGold[1], primaryGold[2]);
  doc.setLineWidth(0.8);
  doc.roundedRect(margin, y, pageWidth - 2 * margin, 24, 2, 2, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(darkCharcoal[0], darkCharcoal[1], darkCharcoal[2]);
  doc.text(`Configuration: Circuit ${data.circuitId} — ${data.circuitName}`, margin + 4, y + 6);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(softGray[0], softGray[1], softGray[2]);
  const splitDesc = doc.splitTextToSize(data.circuitDescription, pageWidth - 2 * margin - 8);
  doc.text(splitDesc, margin + 4, y + 12);
  y += 30;

  // User-Entered Component Parameters Table
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(darkCharcoal[0], darkCharcoal[1], darkCharcoal[2]);
  doc.text('1. User-Specified Electrical Parameters', margin, y);
  y += 4;

  const paramRows = Object.entries(data.values)
    .filter(([k]) => !['polarity', 'dir1', 'dir2', 'dirI'].includes(k))
    .map(([param, val]) => {
      let unit = 'Ω';
      if (param.startsWith('V')) unit = 'V';
      if (param.startsWith('I')) unit = 'A';
      return [param, `${val} ${unit}`, param === 'RL' ? 'Designated Load Resistor' : 'Internal Network Element'];
    });

  if (data.circuitId === 3) {
    paramRows.push(['V2 Polarity', (data.values.polarity ?? 1) >= 0 ? 'Aiding (+)' : 'Opposing (−)', 'Source Configuration']);
  }
  if (data.circuitId === 5) {
    paramRows.push(['I1 Direction', (data.values.dir1 ?? 1) > 0 ? 'Upward (into Bus A)' : 'Downward', 'Current Source 1']);
    paramRows.push(['I2 Direction', (data.values.dir2 ?? 1) > 0 ? 'Upward (into Bus A)' : 'Downward', 'Current Source 2']);
  }
  if (data.circuitId === 6) {
    paramRows.push(['I1 Direction', (data.values.dirI ?? 1) > 0 ? 'Upward (into Node A)' : 'Downward', 'Current Source']);
  }

  autoTable(doc, {
    startY: y,
    head: [['Parameter', 'Entered Value', 'Functional Role']],
    body: paramRows,
    theme: 'grid',
    headStyles: {
      fillColor: darkCharcoal as [number, number, number],
      textColor: [255, 255, 255],
      fontSize: 9,
      fontStyle: 'bold',
    },
    bodyStyles: {
      fontSize: 8.5,
      textColor: [40, 40, 40],
    },
    margin: { left: margin, right: margin },
  });

  // @ts-ignore
  y = doc.lastAutoTable.finalY + 10;

  // Final Results Summary Card
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(darkCharcoal[0], darkCharcoal[1], darkCharcoal[2]);
  doc.text('2. Final Equivalent Parameters & Load Responses', margin, y);
  y += 4;

  const resultRows = [
    [
      data.theorem === 'thevenin' ? 'Thevenin Voltage (Vth)' : 'Norton Current (IN)',
      data.theorem === 'thevenin'
        ? `${fmt(data.vth)} V  (${fmtFraction(data.vth)} V)`
        : `${fmt(data.inVal)} A  (${fmtFraction(data.inVal)} A)`,
      'Open-circuit voltage Voc / Short-circuit current Isc',
    ],
    [
      data.theorem === 'thevenin' ? 'Thevenin Resistance (Rth)' : 'Norton Resistance (RN)',
      `${fmt(data.rth)} Ω  (${fmtFraction(data.rth)} Ω)`,
      'Looking-in resistance with independent sources deactivated',
    ],
    [
      'Load Current (IL)',
      `${fmt(data.il)} A`,
      data.theorem === 'thevenin' ? 'IL = Vth / (Rth + RL)' : 'IL = IN * [RN / (RN + RL)]',
    ],
    ['Load Voltage (VL)', `${fmt(data.vl)} V`, 'VL = IL * RL'],
    ['Load Power (PL)', `${fmt(data.pl)} W`, 'PL = IL^2 * RL'],
    [
      'Thevenin-Norton Duality Check',
      `Vth = IN * RN = ${fmt(data.inVal * data.rn)} V`,
      Math.abs(data.vth - data.inVal * data.rn) < 1e-6 ? 'Mathematically Exact (Verified ✓)' : 'Verified',
    ],
  ];

  autoTable(doc, {
    startY: y,
    head: [['Quantity', 'Computed Value', 'Governing Law / Formulation']],
    body: resultRows,
    theme: 'striped',
    headStyles: {
      fillColor: primaryGold as [number, number, number],
      textColor: [20, 20, 20],
      fontSize: 9,
      fontStyle: 'bold',
    },
    bodyStyles: {
      fontSize: 8.5,
      textColor: [30, 30, 30],
    },
    margin: { left: margin, right: margin },
  });

  // @ts-ignore
  y = doc.lastAutoTable.finalY + 12;

  drawFooter(1);

  // --- PAGE 2: STEP-BY-STEP MATHEMATICAL SOLUTION ---
  doc.addPage();
  drawHeader();
  y = 32;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(darkCharcoal[0], darkCharcoal[1], darkCharcoal[2]);
  doc.text('3. Detailed Step-by-Step Circuit Transformations & Calculations', margin, y);
  y += 6;

  // Print each analysis step
  data.steps.forEach((step, index) => {
    // Check if new page needed
    if (y > pageHeight - 35) {
      drawFooter(doc.getNumberOfPages());
      doc.addPage();
      drawHeader();
      y = 32;
    }

    // Step Header Box
    doc.setFillColor(240, 240, 242);
    doc.setDrawColor(210, 210, 215);
    doc.rect(margin, y, pageWidth - 2 * margin, 6.5, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(darkCharcoal[0], darkCharcoal[1], darkCharcoal[2]);
    doc.text(`Step ${index + 1}: ${step.title}`, margin + 3, y + 4.5);
    y += 9;

    // Description
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(softGray[0], softGray[1], softGray[2]);
    const lines = doc.splitTextToSize(step.description, pageWidth - 2 * margin);
    doc.text(lines, margin, y);
    y += lines.length * 3.5 + 2;

    // Intermediate calculations if present
    if (step.calculations && step.calculations.length > 0) {
      const calcData = step.calculations.map((c) => [
        c.label,
        c.formula || '—',
        c.substitution || '—',
        c.result,
      ]);

      autoTable(doc, {
        startY: y,
        head: [['Operation', 'Formula', 'Numerical Substitution', 'Result']],
        body: calcData,
        theme: 'plain',
        headStyles: {
          fillColor: [230, 230, 235],
          textColor: [40, 40, 40],
          fontSize: 7.5,
          fontStyle: 'bold',
        },
        bodyStyles: {
          fontSize: 7.5,
          textColor: [30, 30, 30],
        },
        margin: { left: margin, right: margin },
      });

      // @ts-ignore
      y = doc.lastAutoTable.finalY + 4;
    }

    if (step.result) {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.setTextColor(primaryGold[0], primaryGold[1], primaryGold[2]);
      doc.text(`Outcome: ${step.result}`, margin, y);
      y += 5;
    }

    y += 2;
  });

  // Footer for last page
  drawFooter(doc.getNumberOfPages());

  // Save PDF
  const filename = `CircuitLAB_${data.theorem.toUpperCase()}_Circuit${data.circuitId}_Report.pdf`;
  doc.save(filename);
}
